// VoiceTag – safe bridge between the window and the computer
'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  isDesktop: true,
  openVideo: () => ipcRenderer.invoke('open-video'),
  registerMedia: p => ipcRenderer.invoke('register-media', p),
  pathForFile: file => { try { return webUtils.getPathForFile(file); } catch (e) { return ''; } },
  mediaUrl: p => 'app://voicetag/__media?p=' + encodeURIComponent(p),
  saveFile: opts => ipcRenderer.invoke('save-file', opts),
  openTextFile: opts => ipcRenderer.invoke('open-text-file', opts),
  openTextFiles: opts => ipcRenderer.invoke('open-text-files', opts),
  readTextFiles: paths => ipcRenderer.invoke('read-text-files', paths),
  openExternal: url => ipcRenderer.invoke('open-external', url),
  appVersion: () => ipcRenderer.invoke('app-version'),
  exportPdf: opts => ipcRenderer.invoke('export-pdf', opts),
  modelInfo: () => ipcRenderer.invoke('model-info'),
  ffmpegInfo: () => ipcRenderer.invoke('ffmpeg-info'),
  showInFolder: p => ipcRenderer.invoke('show-in-folder', p),
  exportClips: opts => ipcRenderer.invoke('export-clips', opts),
  cancelExport: () => ipcRenderer.invoke('cancel-export'),
  onExportProgress: cb => ipcRenderer.on('export-progress', (e, p) => cb(p)),
  convertVideo: p => ipcRenderer.invoke('convert-video', p),
  cachedConversion: p => ipcRenderer.invoke('cached-conversion', p),
  cancelConvert: () => ipcRenderer.invoke('cancel-convert'),
  onConvertProgress: cb => ipcRenderer.on('convert-progress', (e, p) => cb(p)),
  chooseDirectory: t => ipcRenderer.invoke('choose-directory', t),
  defaultProjectsDir: () => ipcRenderer.invoke('default-projects-dir'),
  createProject: o => ipcRenderer.invoke('create-project', o),
  writeProject: o => ipcRenderer.invoke('write-project', o),
  readProject: f => ipcRenderer.invoke('read-project', f),
  listBackups: f => ipcRenderer.invoke('list-backups', f),
  pathExists: p => ipcRenderer.invoke('path-exists', p),
  writeBinary: o => ipcRenderer.invoke('write-binary', o),
  writeText: o => ipcRenderer.invoke('write-text', o),
  copyIntoProject: o => ipcRenderer.invoke('copy-into-project', o),
  probeVideo: p => ipcRenderer.invoke('probe-video', p),
  systemInfo: () => ipcRenderer.invoke('system-info'),
  aiInfo: () => ipcRenderer.invoke('ai-info'),
  aiAnalyse: o => ipcRenderer.invoke('ai-analyse', o),
  aiScan: o => ipcRenderer.invoke('ai-analyse', Object.assign({}, o, { scan: true })),
  aiCancel: () => ipcRenderer.invoke('ai-cancel'),
  v3dBegin: o => ipcRenderer.invoke('v3d-begin', o),
  v3dFrame: bytes => ipcRenderer.invoke('v3d-frame', bytes),
  v3dEnd: o => ipcRenderer.invoke('v3d-end', o || {}),
  onAiProgress: cb => { ipcRenderer.removeAllListeners('ai-progress'); ipcRenderer.on('ai-progress', (e, p) => cb(p)); },
  pendingFile: () => ipcRenderer.invoke('pending-file'),
  onOpenFile: cb => ipcRenderer.on('open-file', (e, f) => cb(f)),
  onClosing: cb => ipcRenderer.on('app-closing', () => cb())
});
